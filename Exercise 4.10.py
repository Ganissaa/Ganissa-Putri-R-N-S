# Menggunakan daftar pizza dari latihan sebelumnya
daftar_pizza = ['pepperoni', 'meat lovers', 'super supreme', 'Chessy']

# pertama
print("Tiga item pertama dalam list adalah:")
print(daftar_pizza[:3])

# tengah
print("\nTiga item dari tengah list adalah:")
print(daftar_pizza[1:4])

# terakhir
print("\nTiga item terakhir dalam list adalah:")
print(daftar_pizza[-3:])