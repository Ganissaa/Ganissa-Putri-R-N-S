# Mendefinisikan fungsi dengan satu parameter 'title'
def favorite_book(title):
    """Fungsi ini mencetak buku favorit berdasarkan judul yang dimasukkan."""
    print(f"Salah satu buku favoritku adalah {title}.")

# Memanggil fungsi dan memasukkan argumen judul buku
favorite_book('Alice in Wonderland')